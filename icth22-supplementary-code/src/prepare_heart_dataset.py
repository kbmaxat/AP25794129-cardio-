"""Prepare and optionally materialize augmented Heart Database samples."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import shutil
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

from .augmentation import (
    augment_pair,
    parameters_as_dict,
    sample_parameters,
    validate_pair,
)
from .heart_database import discover_samples, load_sample, sha256_file


SOURCE_URL = "https://www.laurentnajman.org/heart/H_data.html"
SOURCE_ARCHIVE_MD5 = "8ff8a93358a77f1f29e34ae71b4ab281"


def stable_seed(seed: int, *parts: str) -> int:
    payload = ":".join((str(seed), *parts)).encode("utf-8")
    return int.from_bytes(hashlib.sha256(payload).digest()[:8], "big")


def build_folds(patient_ids: list[str], n_folds: int, seed: int) -> list[list[str]]:
    if n_folds < 3 or n_folds > len(patient_ids):
        raise ValueError("n_folds must be between 3 and the patient count")
    shuffled = list(patient_ids)
    np.random.default_rng(seed).shuffle(shuffled)
    return [sorted(shuffled[index::n_folds]) for index in range(n_folds)]


def split_for_fold(folds: list[list[str]], fold_index: int) -> dict[str, list[str]]:
    test = set(folds[fold_index])
    validation = set(folds[(fold_index + 1) % len(folds)])
    all_patients = set().union(*map(set, folds))
    return {
        "train": sorted(all_patients - test - validation),
        "validation": sorted(validation),
        "test": sorted(test),
    }


def save_npz(
    path: Path,
    image: np.ndarray,
    label: np.ndarray,
    expert2_label: np.ndarray | None = None,
) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload: dict[str, np.ndarray] = {"image": image, "label": label}
    if expert2_label is not None:
        payload["expert2_label"] = expert2_label
    np.savez_compressed(path, **payload)
    return sha256_file(path)


def dice_score(first: np.ndarray, second: np.ndarray, class_id: int) -> float:
    first_mask = first == class_id
    second_mask = second == class_id
    denominator = int(first_mask.sum() + second_mask.sum())
    if denominator == 0:
        return 1.0
    return float(2.0 * np.logical_and(first_mask, second_mask).sum() / denominator)


def create_qc_figure(records: list[dict], output_root: Path) -> None:
    selected = records[: min(8, len(records))]
    if not selected:
        return
    figure, axes = plt.subplots(len(selected), 2, figsize=(7, 3 * len(selected)))
    axes = np.atleast_2d(axes)
    for row, record in enumerate(selected):
        with np.load(output_root / record["relative_path"]) as data:
            image = data["image"]
            label = data["label"]
        areas = np.sum(label > 0, axis=(1, 2))
        z_index = int(np.argmax(areas))
        axes[row, 0].imshow(image[z_index], cmap="gray")
        axes[row, 0].set_title(record["generated_id"])
        axes[row, 1].imshow(image[z_index], cmap="gray")
        axes[row, 1].imshow(
            np.ma.masked_where(label[z_index] == 0, label[z_index]),
            cmap="viridis",
            alpha=0.45,
            vmin=0,
            vmax=2,
        )
        axes[row, 1].set_title(f"labels, z={z_index}")
        for axis in axes[row]:
            axis.axis("off")
    figure.tight_layout()
    figure.savefig(output_root / "qc_contact_sheet.png", dpi=160)
    plt.close(figure)


def write_manifest(output_root: Path, records: list[dict]) -> None:
    jsonl_path = output_root / "manifest.jsonl"
    with jsonl_path.open("w", encoding="utf-8") as stream:
        for record in records:
            stream.write(json.dumps(record, ensure_ascii=True, sort_keys=True) + "\n")

    fields = [
        "generated_id",
        "source_sample_id",
        "patient_id",
        "phase",
        "split",
        "kind",
        "relative_path",
        "sha256",
    ]
    with (output_root / "manifest.csv").open(
        "w", encoding="utf-8", newline=""
    ) as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(records)


def prepare(args: argparse.Namespace) -> None:
    dataset_root = args.dataset_root.resolve()
    output_root = args.output.resolve()
    if output_root.exists():
        if not args.overwrite:
            raise FileExistsError(
                f"{output_root} exists; use --overwrite for generated output"
            )
        marker = output_root / ".generated-heart-dataset"
        if not marker.is_file():
            raise ValueError(f"Refusing to remove unmarked directory {output_root}")
        shutil.rmtree(output_root)
    output_root.mkdir(parents=True)
    (output_root / ".generated-heart-dataset").write_text(
        "Generated by src.prepare_heart_dataset\n", encoding="ascii"
    )

    samples = discover_samples(dataset_root)
    patient_ids = sorted({sample.patient_id for sample in samples})
    folds = build_folds(patient_ids, args.folds, args.seed)
    selected_split = split_for_fold(folds, args.fold_index)
    split_by_patient = {
        patient: split
        for split, patients in selected_split.items()
        for patient in patients
    }

    split_document = {
        "strategy": "patient-level cross-validation",
        "seed": args.seed,
        "selected_fold": args.fold_index,
        "folds": folds,
        "selected_split": selected_split,
    }
    (output_root / "splits.json").write_text(
        json.dumps(split_document, indent=2, sort_keys=True) + "\n",
        encoding="ascii",
    )

    records: list[dict] = []
    augmented_records: list[dict] = []
    expert_agreement: list[dict[str, float | str]] = []
    for sample in samples:
        image, expert1, expert2 = load_sample(sample)
        base_qc = validate_pair(image, expert1)
        agreement = {
            "sample_id": sample.sample_id,
            "cavity_dice": dice_score(expert1, expert2, 1),
            "myocardium_dice": dice_score(expert1, expert2, 2),
        }
        expert_agreement.append(agreement)
        base_qc["expert_agreement"] = agreement
        split = split_by_patient[sample.patient_id]
        base_relative = Path("base") / split / f"{sample.sample_id}.npz"
        base_sha = save_npz(
            output_root / base_relative, image, expert1, expert2_label=expert2
        )
        records.append(
            {
                "generated_id": sample.sample_id,
                "source_sample_id": sample.sample_id,
                "patient_id": sample.patient_id,
                "phase": sample.phase,
                "split": split,
                "kind": "base",
                "relative_path": base_relative.as_posix(),
                "sha256": base_sha,
                "source_image_sha256": sha256_file(sample.image_path),
                "source_paths": {
                    "image": str(sample.image_path.relative_to(dataset_root)),
                    "expert1_endocardium": str(
                        sample.expert1_endo_path.relative_to(dataset_root)
                    ),
                    "expert1_epicardium": str(
                        sample.expert1_epi_path.relative_to(dataset_root)
                    ),
                    "expert2_endocardium": str(
                        sample.expert2_endo_path.relative_to(dataset_root)
                    ),
                    "expert2_epicardium": str(
                        sample.expert2_epi_path.relative_to(dataset_root)
                    ),
                },
                "qc": base_qc,
            }
        )

        if split != "train":
            continue
        for copy_index in range(1, args.copies + 1):
            generated_id = f"{sample.sample_id}__aug{copy_index:02d}"
            item_seed = stable_seed(
                args.seed, sample.patient_id, sample.phase, str(copy_index)
            )
            rng = np.random.default_rng(item_seed)
            parameters = sample_parameters(rng)
            augmented_image, augmented_label = augment_pair(
                image, expert1, parameters, rng
            )
            qc = validate_pair(augmented_image, augmented_label, expert1)
            relative_path = Path("augmented") / "train" / f"{generated_id}.npz"
            generated_sha = save_npz(
                output_root / relative_path, augmented_image, augmented_label
            )
            record = {
                "generated_id": generated_id,
                "source_sample_id": sample.sample_id,
                "patient_id": sample.patient_id,
                "phase": sample.phase,
                "split": "train",
                "kind": "augmented",
                "relative_path": relative_path.as_posix(),
                "sha256": generated_sha,
                "seed": item_seed,
                "transforms": parameters_as_dict(parameters),
                "qc": qc,
            }
            records.append(record)
            augmented_records.append(record)

    write_manifest(output_root, records)
    create_qc_figure(augmented_records, output_root)
    agreement_summary = {
        metric: {
            "mean": float(np.mean([row[metric] for row in expert_agreement])),
            "std": float(np.std([row[metric] for row in expert_agreement])),
            "min": float(np.min([row[metric] for row in expert_agreement])),
            "max": float(np.max([row[metric] for row in expert_agreement])),
        }
        for metric in ("cavity_dice", "myocardium_dice")
    }
    (output_root / "expert_agreement.json").write_text(
        json.dumps(
            {"samples": expert_agreement, "summary": agreement_summary},
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="ascii",
    )
    summary = {
        "source_url": SOURCE_URL,
        "expected_source_archive_md5": SOURCE_ARCHIVE_MD5,
        "patients": len(patient_ids),
        "base_samples": len(samples),
        "augmented_train_samples": len(augmented_records),
        "total_npz_files": len(records),
        "class_definition": {
            "0": "background",
            "1": "left ventricular cavity",
            "2": "myocardium",
        },
        "augmentation_scope": "training split only",
        "expert_agreement": agreement_summary,
    }
    (output_root / "summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="ascii"
    )
    print(json.dumps(summary, indent=2))


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--dataset-root",
        type=Path,
        default=Path("data/data/raw/HeartDatabase/HeartDatabase"),
    )
    parser.add_argument("--output", type=Path, default=Path("data/heart_prepared"))
    parser.add_argument("--seed", type=int, default=25794129)
    parser.add_argument("--folds", type=int, default=5)
    parser.add_argument("--fold-index", type=int, default=0)
    parser.add_argument(
        "--copies",
        type=int,
        default=4,
        help="Materialized augmented copies per training sample",
    )
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    if not 0 <= args.fold_index < args.folds:
        parser.error("--fold-index must be in [0, folds)")
    if args.copies < 0:
        parser.error("--copies must be non-negative")
    return args


if __name__ == "__main__":
    prepare(parse_args())
